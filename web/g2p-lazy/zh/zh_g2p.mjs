const QUOTES = /["“”]/gu;
const ZH_BOUNDARY = /(?:[。！？]|……|…)+[”’」』）》】〕〉）]*/u;
const ASCII_BOUNDARY = new RegExp(
  "(?:[.!?\\u2026]|[\\u061F]|[\\u0964\\u0965])+['\"\\)\\]\\}\\u2019\\u201D\\u00BB]*", "gu");
const ASCII_LOOKAHEAD_NUMBER = new RegExp(
  "^[" + PY_SPACE + "]+[" + ND + "]+[.)]{1,2}[" + PY_SPACE + "]+", "u");
const BLANK_LINES = /(?:\r?\n){2,}/u;

const WORD_ASTERISKS = /\*+([^*]+)\*+/gu;
// Python's `(?:\A|(?<=\n))`: without the m flag, `^` is \A.
const LINE_ASTERISKS = new RegExp("(?:^|(?<=\\n))[" + PY_SPACE + "]*\\*+", "gu");

const removeAsterisks = (text) =>
  text.replace(WORD_ASTERISKS, "$1").replace(LINE_ASTERISKS, "");

/** sentence-stream's ABBREVIATION_RE: `\b\p{Lu}(?:\p{L}{1,2})?\.$`. */
function isAbbreviation(tail) {
  if (!tail.endsWith(".")) return false;
  const stem = cps(tail.slice(0, -1));
  for (const length of [1, 2, 3]) {
    if (stem.length < length) break;
    const candidate = stem.slice(stem.length - length);
    if (!isLu(candidate[0])) continue;
    if (candidate.slice(1).some((c) => !isLetter(c))) continue;
    const before = stem.slice(0, stem.length - length);
    if (before.length) {
      const last = before[before.length - 1];
      if (isAlnum(last) || last === "_") continue;   // the \b is not satisfied
    }
    return true;
  }
  return false;
}

/** The first ASCII sentence boundary whose lookahead actually holds. */
function asciiBoundary(text) {
  let position = 0;
  for (;;) {
    ASCII_BOUNDARY.lastIndex = position;
    const match = ASCII_BOUNDARY.exec(text);
    if (match === null) return null;
    const start = match.index, end = match.index + match[0].length;
    const rest = text.slice(end);
    const stripped = pyLStrip(rest);
    if (rest !== stripped && stripped && isTitlecase(cps(stripped)[0]))
      return { start, end };
    if (ASCII_LOOKAHEAD_NUMBER.test(rest)) return { start, end };
    position = start + 1;
  }
}

function firstMatch(re, text) {
  const m = re.exec(text);
  return m === null ? null : { start: m.index, end: m.index + m[0].length };
}

/** `sentence_stream.stream_to_sentences([text])`, for one complete string. */
export function splitSentences(text) {
  const sentences = [];
  let remaining = text;
  let current = "";

  while (remaining) {
    const blank = firstMatch(BLANK_LINES, remaining);
    const chinese = firstMatch(ZH_BOUNDARY, remaining);
    const asciiMatch = asciiBoundary(remaining);

    let punctuation;
    if (chinese && asciiMatch) punctuation = chinese.start < asciiMatch.start ? chinese : asciiMatch;
    else punctuation = chinese || asciiMatch;

    let first;
    if (blank && punctuation) first = blank.start < punctuation.start ? blank : punctuation;
    else first = blank || punctuation;
    if (!first) break;
    if (first === chinese && first.end === remaining.length) break;

    const chunk = remaining.slice(0, first.end);
    if (!current) {
      if (isAbbreviation(lastCps(chunk, 5))) {
        current = chunk;
      } else {
        const output = removeAsterisks(pyStrip(chunk));
        if (output) sentences.push(output);
      }
    } else if (isAbbreviation(lastCps(current, 5))) {
      current += chunk;
    } else {
      const output = removeAsterisks(pyStrip(current));
      if (output) sentences.push(output);
      current = chunk;
    }

    if (current && !isAbbreviation(lastCps(current, 5))) {
      const output = removeAsterisks(pyStrip(current));
      if (output) sentences.push(output);
      current = "";
    }

    remaining = remaining.slice(first.end);
  }

  const tail = removeAsterisks(pyStrip(current + remaining));
  if (tail) sentences.push(tail);
  return sentences;
}

// ---------------------------------------------------------------------------
// 2. numbers -> words: CLDR's zh `spellout-numbering`
// ---------------------------------------------------------------------------
//
// The transcription of CLDR's rules is zh_g2p.py's, checked there against
// unicode_rbnf itself on 218,974 inputs. This is a transcription of the
// transcription, checked against the same engine again from Node -- see
// tools/verify_zh_number_expansion_node.mjs. BigInt throughout: 京 is 10^16
// and Number stops being exact at 2^53, so a Number port would round
// 12,345,678,901,234,567 into a different Chinese sentence.

const DIGITS = "〇一二三四五六七八九";

// (scale, unit word, does its private ruleset write a 〇 filler from 20 up,
//  and below what remainder does it write one at all).
const SCALES = [
  [10n ** 16n, "京", true, 10n ** 12n],
  [10n ** 12n, "兆", true, 10n ** 7n],
  [10n ** 8n, "亿", true, 10n ** 4n],
  [10n ** 4n, "万", true, 10n ** 3n],
  [10n ** 3n, "千", true, 10n ** 2n],
  [10n ** 2n, "百", false, 20n],
];

/** One of CLDR's private `number*` rulesets, applied to a nonzero value. */
function remainder(value, zeroFrom20, plainFrom) {
  if (value < 10n) return DIGITS[0] + numbering(value);
  if (value < 20n) return (zeroFrom20 ? DIGITS[0] : "") + DIGITS[1] + numbering(value);
  if (value < plainFrom) return (zeroFrom20 ? DIGITS[0] : "") + numbering(value);
  return numbering(value);
}

/** Python's f"{value:,}" for a non-negative integer. */
function grouped(value) {
  const s = value.toString();
  let out = "";
  for (let i = 0; i < s.length; i++) {
    if (i && (s.length - i) % 3 === 0) out += ",";
    out += s[i];
  }
  return out;
}

/** CLDR zh `spellout-numbering`, for a non-negative integer. */
function numbering(value) {
  if (value >= 10n ** 18n) return grouped(value);   // CLDR's own decimal fallback
  for (const [scale, unit, zeroFrom20, plainFrom] of SCALES) {
    if (value >= scale) {
      const high = value / scale, low = value % scale;
      let out = numbering(high) + unit;
      if (low) out += remainder(low, zeroFrom20, plainFrom);
      return out;
    }
  }
  if (value >= 20n) {
    const high = value / 10n, low = value % 10n;
    return DIGITS[Number(high)] + "十" + (low ? DIGITS[Number(low)] : "");
  }
  if (value >= 10n) {
    const low = value - 10n;
    return "十" + (low ? DIGITS[Number(low)] : "");
  }
  return DIGITS[Number(value)];
}

/** `RbnfEngine.for_language("zh").format_number(text).text`, reproduced. */
export function formatNumber(text) {
  let negative = text.startsWith("-");
  const body = negative ? text.slice(1) : text;
  const dot = body.indexOf(".");
  const whole = dot < 0 ? body : body.slice(0, dot);
  let fraction = dot < 0 ? "" : body.slice(dot + 1);
  const value = pyInt(whole || "0");
  // An all-zero fraction is not spoken: "15.00" -> 十五. Python compares the
  // CHARACTERS against "0", so a fraction of Arabic-Indic zeros is not
  // all-zero to it, and is not to this either.
  if (fraction && cps(fraction).every((c) => c === "0")) fraction = "";
  if (negative && value === 0n && !fraction) negative = false;
  if (fraction) {
    if (negative) {
      // unicode_rbnf's own behaviour: the fraction is dropped for a negative
      // decimal. Reproduced, not endorsed.
      return "负" + (value ? numbering(value) : "");
    }
    return numbering(value) + "点" +
           cps(fraction).map((d) => DIGITS[digitValue(d.codePointAt(0))]).join("");
  }
  const out = numbering(value);
  return negative ? "负" + out : out;
}

// piper's own rewrites, ahead of the generic digit pass.
const TEMPERATURE = new RegExp(
  "(?<sign>[-\\u2212])?(?<num>[" + ND + "]+)[" + PY_SPACE + "]*(?:\\u00B0[" +
  PY_SPACE + "]*C|\\u2103)", "gu");
const PERCENT = new RegExp(
  "(?<num>-?[" + ND + "]+(?:\\.[" + ND + "]+)?|" +
  "[\\u96F6\\u3007\\u4E00\\u4E8C\\u4E09\\u56DB\\u4E94\\u516D\\u4E03\\u516B" +
  "\\u4E5D\\u5341\\u767E\\u5343\\u4E07\\u4EBF\\u4E24\\u70B9]+)[" + PY_SPACE +
  "]*(?:%|\\uFF05)", "gu");
const NUMBER = new RegExp("-?[" + ND + "]+(?:\\.[" + ND + "]+)?", "gu");
const NUMBER_FULL = new RegExp("^(?:-?[" + ND + "]+(?:\\.[" + ND + "]+)?)$", "u");

/** `ChinesePhonemizer._numbers_to_words`. */
export function numbersToWords(text) {
  text = text.replace(TEMPERATURE, (...args) => {
    const groups = args[args.length - 1];
    const words = formatNumber(groups.num);
    // "零下" rather than "负" for a temperature: piper's choice, kept.
    return groups.sign ? `零下${words}度` : `${words}度`;
  });
  text = text.replace(PERCENT, (...args) => {
    const groups = args[args.length - 1];
    const number = groups.num;
    const words = NUMBER_FULL.test(number) ? formatNumber(number) : number;
    return `百分之${words}`;
  });
  return text.replace(NUMBER, (m) => formatNumber(m));
}

