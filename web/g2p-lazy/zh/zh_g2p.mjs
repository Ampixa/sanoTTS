/**
 * pypinyin's resolution, over flat tables instead of the package: the phrase
 * KEYS drive a forward maximum-match segmenter, the phrase VALUES give a
 * reading per character, and the character table is the default for whatever
 * the segmenter left standing alone.
 */
export class Lexicon {
  constructor(tables) {
    this.chars = new Map();
    for (const line of tables.chars.split("\n")) {
      if (!line) continue;
      const tab = line.indexOf("\t");
      this.chars.set(tab < 0 ? line : line.slice(0, tab), tab < 0 ? "" : line.slice(tab + 1));
    }

    this.phrases = new Map();
    for (const line of tables.phrases.split("\n")) {
      if (!line) continue;
      const tab = line.indexOf("\t");
      const phrase = tab < 0 ? line : line.slice(0, tab);
      // Python's "".split(" ") is [""], not []: a line with no readings still
      // produces one (empty) reading, which the None-mapping above swallows.
      this.phrases.set(phrase, (tab < 0 ? "" : line.slice(tab + 1)).split(" "));
    }
    // Keys whose readings are exactly the per-character defaults. Their
    // readings are not stored, but the keys are: the segmenter matches on the
    // key set, so deleting one lets a different phrase win the match.
    for (const phrase of tables.phrase_keys.split("\n")) {
      if (phrase && !this.phrases.has(phrase)) this.phrases.set(phrase, []);
    }

    this.prefixes = new Set();
    for (const phrase of this.phrases.keys()) {
      const chars = cps(phrase);
      let acc = "";
      for (const ch of chars) { acc += ch; this.prefixes.add(acc); }
    }
  }

  /** `pypinyin.seg.mmseg.Seg.cut` in its strict (`no_non_phrases`) mode. */
  *cut(text) {
    let remaining = cps(text);
    while (remaining.length) {
      let lastValidWord = "";
      let lastValidIndex = 0;
      let broke = false;
      for (let index = 0; index < remaining.length; index++) {
        const word = remaining.slice(0, index + 1).join("");
        if (this.prefixes.has(word)) {
          if (this.phrases.has(word)) { lastValidWord = word; lastValidIndex = index + 1; }
        } else {
          if (lastValidWord) {
            yield lastValidWord;
            remaining = remaining.slice(lastValidIndex);
          } else {
            yield remaining[0];
            remaining = remaining.slice(1);
          }
          broke = true;
          break;
        }
      }
      if (broke) continue;
      // Python's for/else: the loop ran out without breaking.
      if (lastValidWord) {
        yield lastValidWord;
        remaining = remaining.slice(lastValidIndex);
      } else {
        const whole = remaining.join("");
        if (!this.phrases.has(whole)) yield* remaining;
        else yield whole;
        return;
      }
    }
  }

  /** One reading per character, `null` where there is no reading. */
  syllables(text) {
    const out = [];
    for (const run of splitHanRuns(text)) {
      if (!RE_HANS.test(run)) {
        for (let i = cps(run).length; i > 0; i--) out.push(null);
        continue;
      }
      for (const word of this.cut(run)) {
        const readings = this.phrases.get(word);
        if (readings && readings.length) out.push(...readings);
        else for (const char of cps(word)) out.push(this.chars.get(char) ?? null);
      }
    }
    return out;
  }
}

/** One pinyin syllable per character of `sentence`, or `null`. */
export function sentenceSyllables(lexicon, sentence) {
  const chars = cps(sentence);
  const raw = lexicon.syllables(sentence);
  // Python: `TEACHER_READINGS.get((char, syllable), syllable) if syllable else None`
  // -- a falsy reading (a table line with no reading at all) becomes None
  // there, so it becomes null here.
  const syllables = raw.map((syllable, index) => {
    if (!syllable) return null;
    const remapped = TEACHER_READINGS.get(chars[index] + "\t" + syllable);
    return remapped === undefined ? syllable : remapped;
  });
  for (let index = 0; index < chars.length; index++) {
    const table = SANDHI.get(chars[index]);
    if (table === undefined || !syllables[index]) continue;
    const following = index + 1 < syllables.length ? syllables[index + 1] : null;
    if (following) syllables[index] = table[following[following.length - 1]];
  }
  return syllables;
}

// ---------------------------------------------------------------------------
// 4. syllable -> phonemes -> ids, piper's own framing
// ---------------------------------------------------------------------------

// Longest first: `zh`/`ch`/`sh` have to beat `z`/`c`/`s`.
const PINYIN_INITIALS = ["zh", "ch", "sh", "b", "p", "m", "f", "d", "t", "n",
  "l", "g", "k", "h", "j", "q", "x", "r", "z", "c", "s", "y", "w"];
const ZERO_INITIAL = "Ø";

const PAD_ID = 0, BOS_ID = 1, EOS_ID = 2;

const SYLLABLE = /^([a-züv:]+?)([1-5])$/u;
const SPLIT_SYLLABLE = /^([a-zvü]+?)([1-5])$/u;

// Ids get a pad after these, not between every symbol.
const GROUP_END_PHONEMES = new Set([
  "1", "2", "3", "4", "5",
  "。", "？", "！", ".", "?", "!",
  "—", "…", "、", "，", "：", "；",
  ",", ":", ";", " ",
]);

/** `_normalize_g2pw_syllable`: the u-umlaut family becomes ASCII `v`. */
export function normalizeSyllable(syllable) {
  const match = SYLLABLE.exec(syllable);
  if (!match) return syllable;
  return match[1].replaceAll("u:", "v").replaceAll("ü", "v") + match[2];
}

/** `hang2` -> `['h', 'ang', '2']`; `ai3` -> `['', 'ai', '3']`. */
export function splitInitialFinalTone(syllable) {
  const match = SPLIT_SYLLABLE.exec(syllable);
  if (!match) return ["", "", null];
  const base = match[1], tone = match[2];
  let initial = "";
  for (const candidate of PINYIN_INITIALS) {
    if (base.startsWith(candidate)) { initial = candidate; break; }
  }
  return [initial, initial ? base.slice(initial.length) : base, tone];
}

/** The inner loop of `ChinesePhonemizer.phonemize`, for one sentence. */
export function sentencePhonemes(sentence, syllables, idMap) {
  const out = [];
  const chars = cps(sentence);
  const n = Math.min(chars.length, syllables.length);
  for (let i = 0; i < n; i++) {
    const char = chars[i];
    let syllable = syllables[i];
    if (syllable === null || syllable === undefined) {
      // Punctuation, or a character with no reading. piper emits it only if
      // the voice has an id for it, and drops it silently otherwise.
      if (Object.prototype.hasOwnProperty.call(idMap, char)) out.push(char);
      continue;
    }
    syllable = normalizeSyllable(syllable);
    const [initial, final, tone] = splitInitialFinalTone(syllable);
    if (!final) {
      // Not a pinyin syllable at all. piper appends it whole, which the id
      // lookup then discards; kept so the two behave the same.
      out.push(syllable);
      continue;
    }
    out.push(initial || ZERO_INITIAL, final, tone);
  }
  return out;
}

/**
 * `piper.phonemize_chinese.phonemes_to_ids` -- NOT the espeak framing. The
 * espeak voices get a pad between every pair of symbols; the pinyin voices get
 * one after each complete syllable (i.e. after its tone) and after each pause.
 * Using the wrong one produces a sequence twice the right length that the
 * duration model has never seen.
 */
export function phonemesToIds(phonemes, idMap) {
  const ids = [BOS_ID];
  let missing = 0;
  for (const phoneme of phonemes) {
    if (!Object.prototype.hasOwnProperty.call(idMap, phoneme)) { missing += 1; continue; }
    ids.push(idMap[phoneme]);
    if (GROUP_END_PHONEMES.has(phoneme)) ids.push(PAD_ID);
  }
  ids.push(EOS_ID);
  return { ids, missing };
}

// ---------------------------------------------------------------------------
// 5. the loader
// ---------------------------------------------------------------------------

async function inflate(bytes) {
  if (typeof DecompressionStream !== "function")
    throw new ZhG2PError("unsupported",
      "this browser has no DecompressionStream; the Chinese lexicon ships gzipped " +
      "(needs Chrome 80, Firefox 113 or Safari 16.4)");
  const stream = new Blob([bytes]).stream().pipeThrough(new DecompressionStream("gzip"));
  return new Uint8Array(await new Response(stream).arrayBuffer());
}

async function sha256Hex(bytes) {
  // crypto.subtle needs a secure context. Over plain http there is no hash to
  // compare against and the byte-length check stands alone -- the same
  // position web/index.html takes for the voice blobs.
  if (typeof crypto === "undefined" || !crypto.subtle) return null;
  const digest = await crypto.subtle.digest("SHA-256", bytes);
  return Array.from(new Uint8Array(digest)).map((b) => b.toString(16).padStart(2, "0")).join("");
}

/**
 * The front end, with its tables. `phonemize`/`textToIds` take the voice's own
 * `phoneme_id_map` (85 symbols, from web/voices/<key>/meta.json) rather than
 * baking one in: the map is a property of the teacher, not of the lexicon.
 */
export class ZhG2P {
  constructor(lexicon) { this.lexicon = lexicon; }

  /** Text -> the flat phoneme list, sentence boundaries already applied. */
  phonemize(text, idMap) {
    if (typeof text !== "string" || !pyStrip(text))
      throw new ZhG2PError("empty", "text must be a non-empty string");
    const phonemes = [];
    for (let sentence of splitSentences(text.replace(QUOTES, ""))) {
      sentence = numbersToWords(sentence);
      phonemes.push(...sentencePhonemes(sentence, sentenceSyllables(this.lexicon, sentence), idMap));
    }
    if (!phonemes.length)
      throw new ZhG2PError("empty", `phonemization produced no symbols for text: ${JSON.stringify(text)}`);
    return phonemes;
  }

  /** Drop-in for the wasm phonemizer: an Int32Array of ids, plus diagnostics. */
  textToIds(text, idMap) {
    const phonemes = this.phonemize(text, idMap);
    const unmapped = [...new Set(phonemes.filter(
      (p) => !Object.prototype.hasOwnProperty.call(idMap, p)))].sort().join(" ");
    const { ids, missing } = phonemesToIds(phonemes, idMap);
    if (ids.length <= 3)
      throw new ZhG2PError("empty", `phonemization produced no usable phonemes for: ${JSON.stringify(text)}`);
    return { ids: Int32Array.from(ids), phonemes, unmapped, missing };
  }
}

/** Build a front end from three already-decoded tables (used by the harness). */
export function createZhG2P(tables) {
  for (const name of ["chars", "phrases", "phrase_keys"]) {
    if (typeof tables[name] !== "string" || !tables[name])
      throw new ZhG2PError("missing_data", `table ${name} is empty or not a string`);
  }
  return new ZhG2P(new Lexicon(tables));
}

/**
 * Fetch web/g2p-lazy/zh/, verify it against its manifest, and build the front
 * end. `fetchFn` is passed explicitly because a bare `fetch` reference
 * detached from window throws "Illegal invocation" in some engines.
 */
export async function loadZhG2P(baseUrl, fetchFn) {
  const base = baseUrl.endsWith("/") ? baseUrl : baseUrl + "/";
  const get = async (path) => {
    const response = await fetchFn(base + path);
    if (!response.ok) throw new ZhG2PError("fetch", `${base + path}: HTTP ${response.status}`);
    return new Uint8Array(await response.arrayBuffer());
  };

  const manifest = JSON.parse(new TextDecoder().decode(await get("manifest.json")));
  const entries = manifest && manifest.files;
  if (!entries) throw new ZhG2PError("corrupt_data", "manifest.json has no files section");

  const decoder = new TextDecoder("utf-8", { fatal: true });
  const tables = {};
  await Promise.all(["chars", "phrases", "phrase_keys"].map(async (name) => {
    const entry = entries[name];
    if (!entry) throw new ZhG2PError("corrupt_data", `manifest.json has no entry for ${name}`);
    const raw = await inflate(await get(entry.file));
    if (raw.length !== entry.raw_bytes)
      throw new ZhG2PError("corrupt_data",
        `${entry.file} inflates to ${raw.length} bytes, manifest says ${entry.raw_bytes}`);
    const got = await sha256Hex(raw);
    if (got && got !== entry.raw_sha256)
      throw new ZhG2PError("corrupt_data",
        `${entry.file} inflates to sha256 ${got}, manifest says ${entry.raw_sha256}`);
    tables[name] = decoder.decode(raw);
  }));

  return createZhG2P(tables);
}
