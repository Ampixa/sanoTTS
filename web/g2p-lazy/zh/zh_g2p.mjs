// Chinese text -> the pinyin phoneme ids `zh_CN-xiao_ya-medium` was distilled
// on. A line-for-line port of pypkg/sanotts/zh_g2p.py, over byte-identical
// tables, with no model of any kind.
//
// WHY THIS FILE EXISTS. Every other voice on the page reaches its ids through
// snt_g2p.wasm, which is espeak-ng. This voice's teacher is not an espeak
// voice: its `phoneme_type` is `pinyin` and its 85-symbol map is reached in
// Piper by g2pW, a 158.8M-parameter BERT that ships as a 152 MB ONNX file --
// fifty times the 3.1 MB voice it would serve, and not something to put in
// front of a web page. pypkg reached the same inventory from two dictionaries
// and twenty lines of lookup; this is that, in JavaScript.
//
// THE CONTRACT. The gate for this port is not "close to Python". Both sides
// are deterministic lookups over the same three tables, so any difference is a
// porting bug, and the harness (tools/verify_zh_g2p_web_node.mjs) demands an
// exact match on every id of every sentence. Where Python and JavaScript
// disagree about the language itself, the Python is the reference and the
// difference is reproduced here rather than tidied up:
//
//   * Python's `\d` and `int()` accept ANY Unicode decimal digit, JavaScript's
//     `\d` is ASCII-only. `４２％` expands in Piper and must expand here. The
//     ND_STARTS table below carries the 76 Unicode decimal ranges so that the
//     regex class and the digit->value conversion are both pinned to the
//     Unicode version the Python was validated against, not to the browser's.
//   * Python's `\s` and `str.strip()` cover \x1c-\x1f and \x85 and do NOT
//     cover ﻿; JavaScript's `\s` and `trim()` are the other way round.
//     PY_SPACE is Python's set, and pyStrip/pyLStrip use it.
//   * Python indexes strings by code point. JavaScript indexes by UTF-16 code
//     unit, and the lexicon reaches into CJK Extension B and beyond. Anything
//     that walks characters here walks code points.
//   * `str.replace` in Python replaces every occurrence; in JavaScript it
//     replaces one. Every port of one is `replaceAll`.
//
// WHAT IT COSTS. 448 KB gzipped, fetched the first time a visitor synthesizes
// Chinese and never otherwise -- nothing here is on the page-load path.

// ---------------------------------------------------------------------------
// Unicode, pinned to the reference implementation
// ---------------------------------------------------------------------------

// unicode_tables.mjs is generated by tools/build_zh_g2p_web_assets.py out of
// the same unicodedata `sanotts.zh_g2p` answers from. It is used INSTEAD of
// the browser's own \p{Lu}/\p{Lo}/... because a browser's Unicode database is
// not the reference's: node 26 ships Unicode 17 against CPython 3.14's 16, and
// the two disagree about 4,659 code points -- 4,658 of them assigned by 17 and
// unknown to 16, plus U+0295, which genuinely moved from Ll to Lo. None of
// that can reach Chinese text, but the ids are a contract, and a contract that
// depends on the browser's release schedule is not one.
import { CATEGORY_RANGES, DECIMAL_DIGIT_STARTS, UNIDATA_VERSION }
  from "./unicode_tables.mjs";

export { UNIDATA_VERSION };
export const ND_STARTS = DECIMAL_DIGIT_STARTS;

/** "41-5A,C0" -> a flat, sorted [start, end, start, end, ...] for bisection. */
function parseRanges(text) {
  const flat = [];
  for (const piece of text.split(",")) {
    const dash = piece.indexOf("-");
    if (dash < 0) { const cp = parseInt(piece, 16); flat.push(cp, cp); }
    else { flat.push(parseInt(piece.slice(0, dash), 16), parseInt(piece.slice(dash + 1), 16)); }
  }
  return flat;
}

function inRanges(flat, cp) {
  let lo = 0, hi = flat.length / 2 - 1;
  while (lo <= hi) {
    const mid = (lo + hi) >> 1;
    if (cp < flat[mid * 2]) hi = mid - 1;
    else if (cp > flat[mid * 2 + 1]) lo = mid + 1;
    else return true;
  }
  return false;
}

const CATS = {};
for (const [name, text] of Object.entries(CATEGORY_RANGES)) CATS[name] = parseRanges(text);

const cpEsc = (cp) => "\\u{" + cp.toString(16).toUpperCase() + "}";
// The character class Python's `\d` denotes, written out. JavaScript's own
// `\d` is ASCII-only, and Piper expands ４２％ because Python's is not.
const ND = ND_STARTS.map((s) => cpEsc(s) + "-" + cpEsc(s + 9)).join("");
// The character class Python's `\s` denotes, which is also exactly the set
// str.isspace() accepts and therefore what str.strip() removes. It covers
// \x1c-\x1f and \x85, which JavaScript's `\s` does not, and does NOT cover
// U+FEFF, which JavaScript's does.
const PY_SPACE = "\\u0009-\\u000D\\u001C-\\u0020\\u0085\\u00A0\\u1680" +
                 "\\u2000-\\u200A\\u2028-\\u2029\\u202F\\u205F\\u3000";

const ND_SORTED = ND_STARTS.slice().sort((a, b) => a - b);

/** Python's int(<one character>) for a decimal digit; -1 if it is not one. */
function digitValue(cp) {
  let lo = 0, hi = ND_SORTED.length - 1, base = -1;
  while (lo <= hi) {
    const mid = (lo + hi) >> 1;
    if (ND_SORTED[mid] <= cp) { base = ND_SORTED[mid]; lo = mid + 1; }
    else hi = mid - 1;
  }
  if (base < 0) return -1;
  const value = cp - base;
  return value <= 9 ? value : -1;
}

/** Python's int() over a run of decimal digits, exactly, at any magnitude. */
function pyInt(digits) {
  let value = 0n;
  for (const ch of digits) {
    const d = digitValue(ch.codePointAt(0));
    if (d < 0) throw new ZhG2PError("bug", `not a decimal digit: ${JSON.stringify(ch)}`);
    value = value * 10n + BigInt(d);
  }
  return value;
}

const isCategory = (name, ch) => inRanges(CATS[name], ch.codePointAt(0));
/** unicodedata.category(c) == "Lu". */
const isLu = (ch) => isCategory("Lu", ch);
/** zh_g2p.py's _TITLECASE_CATEGORIES: {Lu, Lt, Lo}. */
const isTitlecase = (ch) => isCategory("Lu", ch) || isCategory("Lt", ch) || isCategory("Lo", ch);
/** zh_g2p.py's _LETTER_CATEGORIES: {Lu, Ll, Lt, Lm, Lo}. */
const isLetter = (ch) => isCategory("Lu", ch) || isCategory("Ll", ch) ||
                         isCategory("Lt", ch) || isCategory("Lm", ch) || isCategory("Lo", ch);
/** str.isalnum(): alphabetic, or any of the three numeric categories. */
const isAlnum = (ch) => isLetter(ch) || digitValue(ch.codePointAt(0)) >= 0 ||
                        isCategory("Nl", ch) || isCategory("No", ch);

const PY_STRIP_L = new RegExp("^[" + PY_SPACE + "]+", "u");
const PY_STRIP_R = new RegExp("[" + PY_SPACE + "]+$", "u");
const pyLStrip = (s) => s.replace(PY_STRIP_L, "");
const pyStrip = (s) => s.replace(PY_STRIP_L, "").replace(PY_STRIP_R, "");

/** The code points of `s`, as single-code-point strings. Python's list(s). */
const cps = (s) => Array.from(s);
/** Python's s[-n:] over code points. */
function lastCps(s, n) {
  const a = cps(s);
  return a.slice(Math.max(0, a.length - n)).join("");
}

export class ZhG2PError extends Error {
  constructor(kind, message) { super(message); this.name = "ZhG2PError"; this.kind = kind; }
}

