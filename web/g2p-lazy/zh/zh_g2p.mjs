// `pypinyin.constants.RE_HANS`, transcribed code point for code point (it
// carries two private-use ranges, which is why it is not eyeballed).
const RE_HANS = /^(?:[〇-礼㐀-䶿一-鿿豈-﫿\u{20000}-\u{2A6DF}\u{2A703}-\u{2B73F}\u{2B740}-\u{2B81D}\u{2B825}-\u{2BF6E}\u{2C029}-\u{2CE93}\u{2D016}\u{2D11B}-\u{2EBD9}\u{2F80A}-\u{2FA1F}\u{30000}-\u{3134A}\u{300F7}-\u{31288}\u{30EDD}])+$/u;

/** `pypinyin.seg.simpleseg._seg`: alternating Han and non-Han runs. */
function splitHanRuns(text) {
  const runs = [];
  let current = "";
  let currentIsHan = null;
  for (const char of cps(text)) {
    const isHan = RE_HANS.test(char);
    if (currentIsHan === null || isHan === currentIsHan) current += char;
    else { runs.push(current); current = char; }
    currentIsHan = isHan;
  }
  runs.push(current);
  return runs;
}

